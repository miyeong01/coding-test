-- 2022년도 평가 점수가 가장 높은 사원들의 점수, 사번, 성명, 직책, 이메일 조회
-- 평가 점수는 상, 하반기 점수의 합
-- 평가 점수 컬럼 이름은 SCORE

WITH SCORES AS (
    SELECT SUM(SCORE) AS SCORE, E.EMP_NO, E.EMP_NAME, E.POSITION, E.EMAIL
    FROM HR_DEPARTMENT AS D
    JOIN HR_EMPLOYEES AS E
    JOIN HR_GRADE AS G
    ON D.DEPT_ID = E.DEPT_ID AND E.EMP_NO = G.EMP_NO
    WHERE G.YEAR = 2022
    GROUP BY E.EMP_NO)
    
SELECT SCORE, EMP_NO, EMP_NAME, POSITION, EMAIL
FROM SCORES
WHERE SCORE = (SELECT MAX(SCORE) FROM SCORES);

